"""TEMPORARY scaffolding: client-side ``_SecurityClassID`` enrichment for
``Client.list_stocks()``.

``_SecurityClassID`` is confirmed populated by the per-stock
stock-trading-info endpoint (underlying ``Client.stock_info()``/``quote()``)
but always null/absent on ``list_stocks()``'s underlying endpoint. Calling
stock_info() once per stock to enrich every ``list_stocks()`` result would
mean ~510 extra API calls per call (confirmed expensive) — instead, this
loads a one-time, point-in-time snapshot committed at
``src/younit/data/security_classes_snapshot.json`` (generated by
``diagnostics/capture_security_classes.py``) and enriches each
``StockInfo`` from that cache.

CAVEAT: this is client-side, NOT live backend data — see
``StockInfo.security_class_id``/``security_class_name`` docstrings. The
snapshot's capture date is exposed via :func:`snapshot_captured_at` /
``Client.security_class_snapshot_captured_at``.

REMOVAL CHECKLIST (once list_stocks() natively returns _SecurityClassID):
1. Delete this file and ``src/younit/data/security_classes_snapshot.json``.
2. Delete ``diagnostics/capture_security_classes.py``.
3. In client.py: remove the ``_enrich_security_classes(...)`` calls inside
   ``list_stocks()``, the ``security_class_snapshot_captured_at`` property,
   and the ``from younit._security_class_snapshot import ...`` line.
4. In models/market_data.py: drop the "temporary client-side snapshot"
   caveat from ``StockInfo.security_class_id``/``security_class_name``'s
   docstrings (the fields themselves can stay, now populated natively via
   their existing aliases).
5. Delete the enrichment tests (search ``security_class``) in
   tests/unit/test_client.py and tests/unit/test_market_data_models.py.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any

from younit.enums import SECURITY_CLASS_NAMES

_SNAPSHOT_PATH = Path(__file__).parent / "data" / "security_classes_snapshot.json"


@lru_cache(maxsize=1)
def _load_snapshot() -> dict[str, Any]:
    """Load and cache the committed snapshot once per process."""
    try:
        return json.loads(_SNAPSHOT_PATH.read_text(encoding="utf-8"))
    except (FileNotFoundError, json.JSONDecodeError):
        return {"captured_at_utc": None, "stocks": {}}


def snapshot_captured_at() -> str | None:
    """ISO-8601 UTC timestamp of when the snapshot was captured, or None if missing."""
    return _load_snapshot().get("captured_at_utc")


def get_security_class(stock_id: int | None) -> tuple[int | None, str | None]:
    """Look up ``(security_class_id, security_class_name)`` for a stock_id.

    Returns ``(None, None)`` if ``stock_id`` is None or absent from the
    snapshot (e.g. a security listed after the snapshot was captured).
    """
    if stock_id is None:
        return None, None
    entry = _load_snapshot().get("stocks", {}).get(str(stock_id))
    if not entry:
        return None, None
    class_id = entry.get("security_class_id")
    if class_id is None:
        return None, None
    return class_id, SECURITY_CLASS_NAMES.get(class_id)
